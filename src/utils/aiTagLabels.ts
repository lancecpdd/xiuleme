const ZH_TO_EN: Record<string, string[]> = (() => {
  const map: Record<string, string[]> = {};
  for (const [en, label] of Object.entries(AI_TAG_LABELS_ZH)) {
    const key = label.toLowerCase();
    if (!map[key]) map[key] = [];
    if (!map[key].includes(en)) map[key].push(en);
  }
  return map;
})();

function isChineseUiLanguage(language?: string | null): boolean {
  if (!language) return false;
  return language === 'zh-CN' || language === 'zh-TW' || language.startsWith('zh');
}

/** Display label for an AI/user tag value (without user: / color: prefixes). */
export function getAiTagDisplayLabel(tag: string, language?: string | null): string {
  const raw = tag.trim();
  if (!raw) return raw;
  if (!isChineseUiLanguage(language)) return raw;
  return AI_TAG_LABELS_ZH[raw.toLowerCase()] ?? AI_TAG_LABELS_ZH[raw] ?? raw;
}

/**
 * Expand a search term so Chinese labels also match stored English AI tags.
 * Always includes the original term (lowercased).
 */
export function expandTagSearchTerms(term: string): string[] {
  const value = term.trim().toLowerCase();
  if (!value) return [];
  const terms = new Set<string>([value]);
  const enFromZh = ZH_TO_EN[value];
  if (enFromZh) {
    for (const en of enFromZh) terms.add(en.toLowerCase());
  }
  const zhFromEn = AI_TAG_LABELS_ZH[value];
  if (zhFromEn) terms.add(zhFromEn.toLowerCase());
  return [...terms];
}
